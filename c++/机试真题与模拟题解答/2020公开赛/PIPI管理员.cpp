/*
问题 A: PIPI管理员
来源：PIPIOJ 2020 公开赛 (http://pipioj.online/problem.php?cid=1012&pid=0)
时间限制: 1 Sec  内存限制: 128 MB

- 题目描述
PIPI管理着两个仓库，两个仓库每天都会生产总数相同的 a、b 两种产品。
两个仓库生产完之后，PIPI需要通过交换使两个仓库的产品个数一致、排列也相同。
交换只能发生在两个仓库之间（每次取 A 仓库的某件产品和 B 仓库的某件产品互换），
同一个仓库内部不能交换。求最少交换次数；若无法做到，输出 -1。

例如 A 仓库生产 "ab"，B 仓库生产 "ba"：
1. A 的 a 与 B 的 b 交换 → A="bb", B="aa"
2. A 的第一件 b 与 B 的第二件 a 交换 → 两仓库都变成 "ab"
共需 2 次。

- 输入
多组数据，每组包含两个字符串（长度不超过50000）。

- 输出
输出最少交换次数；若两仓库 a、b 产品数量无法达到一致，输出 -1。

- 样例输入
aabbababaa
abbabaaaba
aa
ba

- 样例输出
4
-1

========================================
【解析】
1. 交换只能在两个仓库之间进行，所以每个位置由(A[i],B[i])组成的"配对类型"
   只能按固定方式转化。设：
        p = 满足 A[i]='a' 且 B[i]='b' 的位置数（记为 "ab" 型错位）
        q = 满足 A[i]='b' 且 B[i]='a' 的位置数（"ba" 型错位）
   交换一次是拿 A 仓库的一件产品换 B 仓库的一件产品。
2. 关键结论一（可解条件）：每次交换都是 A、B 两仓库各拿出一件，两边产品
   总量不变；最终要求 A=B，即两仓库中 a 的数量都等于总数的一半。
   因此总数中 a 的个数必须是偶数。用 p、q 表示：a 的总数 = p+q+2×(已配对)，
   所以 a 总数为偶数 ⟺ (p+q) 为偶数。若 p+q 为奇数，输出 -1。
   （验证样例 aa/ba：p=1,q=0，p+q=1 为奇数 → -1 ✓）
3. 关键结论二（交换次数下界）：
   - 一次交换恰好改变两个仓库各一个位置，最多"修好"两个错位：
     用 A 仓库的 a（ab 型位置）换 B 仓库的 b（另一个 ab 型位置），
     两个 ab 型错位同时修复；同理一次交换可修复两个 ba 型错位。
   - 但当 p 为奇数时（q 也必为奇数），各剩一个 ab 型和一个 ba 型错位，
     谁也无法与谁配对，必须先用一次交换把错位"换型"（如题面例子：
     拿 A 的 a 换 B 的 b，使 ab 型变成 ba 型），这一步不修任何错位。
   因此最少次数 = ⌈p/2⌉ + ⌈q/2⌉。
4. 验证样例：
   - aabbababaa / abbabaaaba：逐位比较得 p=3（位置2,5,9），q=3（位置4,6,8），
     答案 = ⌈3/2⌉+⌈3/2⌉ = 2+2 = 4 ✓。
   - aa / ba：p=1，q=0，p+q=1 为奇数 → -1 ✓。
   - 题面例子 ab/ba：p=1,q=1 → 2 ✓。
5. 复杂度 O(|s|)，字符串长 5e4，多组数据也轻松通过。
*/
#include <iostream>
#include <string>
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    string a, b;
    while (cin >> a >> b) {
        int n = a.size(), m = b.size();
        if (n != m) { cout << -1 << "\n"; continue; } // 长度不同永远无法排列一致
        int p = 0, q = 0;
        for (int i = 0; i < n; i++) {
            if (a[i] == 'a' && b[i] == 'b') p++; // "ab" 型错位
            if (a[i] == 'b' && b[i] == 'a') q++; // "ba" 型错位
        }
        if ((p + q) % 2 == 1) cout << -1 << "\n";    // a 产品总数为奇数，无法平分
        else cout << (p + 1) / 2 + (q + 1) / 2 << "\n";
    }
    return 0;
}
