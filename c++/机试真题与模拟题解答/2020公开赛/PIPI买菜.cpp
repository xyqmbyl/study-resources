/*
问题 E: PIPI买菜
来源：PIPIOJ 2020 公开赛 (http://pipioj.online/problem.php?cid=1012&pid=4)
时间限制: 1 Sec  内存限制: 128 MB

- 题目描述
PIPI去菜市场买菜，菜篮子里装着区间 [L,R] 中的所有正整数（即 L, L+1, ...,
R 各一个）。PIPI想从中选出至多 K 个数（不能不选），使得它们的异或和
尽可能小。请输出这个最小的异或和。

- 输入
单组输入，一行三个整数 L, R, K (0<=L<=R<=1e12, 1<=K<=R-L+1)。

- 输出
输出一个正整数表示最小的异或和。

- 样例输入
8 15 3

- 样例输出
1

========================================
【解析】
本题数据范围 L,R<=1e12 且区间长度可达 1e12，必须用数学结论 O(log) 求解。
记 n = R-L+1（区间元素个数），逐段分析：

1. K=1：只能选一个数，最小异或和就是 L 本身。

2. n=1：同理输出 L。

3. n=2：只有 {L, L+1} 和单元素两种选法，答案 = min(L, L^(L+1))。
   相邻数 L 与 L+1 的异或：若 L 为偶数，L^(L+1)=1；若 L 为奇数且末尾有
   t 个连续的 1，则 L^(L+1) = 2^(t+1)-1（可能比 L 大，所以要取 min）。

4. n>=3 且 K=2：答案必为 1。因为 n>=3 时区间内必含相邻的偶数 e 和奇数
   e+1（偶数的末位是 0，异或后末位为 1），{e, e+1} 的异或和为 1，而异或
   和不可能小于 0，也不能做到 0（两个不同的数 x^y=0 意味着 x=y）。

5. n>=3 且 K>=3：答案只可能是 0 或 1（理由同上，总存在相邻偶奇对
   给出 1）。问题变成：[L,R] 中是否存在一个大小 <= K 的子集异或和为 0。
   - 大小为 1、2 的零子集不存在（元素互不相同）。
   - 大小为 3（零三元组 {a,b,a^b}）：任何零三元组中恰有两个数具有相同的
     最高位 p（2 的幂），设它们为 x=p+u, y=p+v，则第三个数 z=u^v < p。
     若 z>=L（否则无法选取），则 x=p+u>=z+1>p... 即 p 必须 >= L+1 且
     p<=R，且需在 [0, R-p] 中存在一对异或值 >= L 的数。而 [0,m] 中两数
     异或的最大值是 2^ceil(lg(m+1))-1（取 0 与全 1 数），它 >= L 当且仅当
     R-p >= np(L)/2（np(L) 为大于 L 的最小 2 的幂）。于是：
        存在零三元组 ⟺ 存在 2 的幂 p 满足 L<p<=R 且 R-p >= np(L)/2
                    ⟺ R >= np(L) + np(L)/2 = 1.5 * np(L)
     （取 p=np(L) 最优。）暴力枚举验证 L<=40、n<=25 共 1000 个区间全部吻合。
   - 大小为 4（两个不相交且异或相等的数对）：当 n>=5 时必存在——取两个
     不相交的相邻偶奇对 {e,e+1} 与 {e+2,e+3}（e 为偶数），两对异或值都是 1；
     当 n=4 时，仅当 L≡0 或 2 (mod 4) 时存在（L≡0 时四个数全异或为 0；
     L≡2 时 {L,L+1} 与 {L+2,L+3} 两对异或均为 1），L≡1 或 3 时不存在
     （同样经暴力验证）。注意：零三元组无法"加一个数"扩成零四元组。
6. 综合算法：
        n = R-L+1
        K==1 或 n==1  -> 输出 L
        n==2          -> 输出 min(L, L^(L+1))
        K==2          -> 输出 1
        K>=3          -> 若 (R >= 1.5*np(L)) 或 (K>=4 且 (n>=5 或 n==4 且
                         L%4∈{0,2})) 输出 0，否则输出 1
   np(L) 为大于 L 的最小 2 的幂。全解 O(log R)。
7. 验证样例：L=8, R=15, K=3。np(8)=16，1.5*np=24 > 15，无零三元组；
   n=8>=5 但 K=3<4 不能用四元组，故答案为 1 ✓
   （例如选 {8,9}，异或和 = 1）。
*/
#include <iostream>
using namespace std;

typedef long long ll;

// 大于 x 的最小 2 的幂
ll npow(ll x) {
    ll p = 1;
    while (p <= x) p <<= 1;
    return p;
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    ll L, R, K;
    if (cin >> L >> R >> K) {
        ll n = R - L + 1;
        if (K == 1 || n == 1) {
            cout << L << "\n";
        } else if (n == 2) {
            ll a = L, b = L ^ (L + 1);
            cout << (a < b ? a : b) << "\n";
        } else if (K == 2) {
            cout << 1 << "\n";
        } else {                       // K >= 3, n >= 3
            bool tri = (R * 2 >= 3 * npow(L));   // 存在零三元组
            bool z4  = (n >= 5) || (n == 4 && L % 4 != 1 && L % 4 != 3);
            bool zero = tri || (K >= 4 && z4);
            cout << (zero ? 0 : 1) << "\n";
        }
    }
    return 0;
}
