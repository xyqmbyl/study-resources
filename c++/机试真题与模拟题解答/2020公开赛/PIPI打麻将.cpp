/*
问题 B: PIPI打麻将
来源：PIPIOJ 2020 公开赛 (http://pipioj.online/problem.php?cid=1012&pid=1)
时间限制: 1 Sec  内存限制: 128 MB

- 题目描述
PIPI麻将供四人游玩，每次只进行八局。麻将桌是正方形，四条边刻有方位，
每条边的方位按逆时针顺序是：东、南、西、北。每一局结束时桌子按逆时针
方向旋转（若这一局自己是南，下一局自己是东）；自己所在边刻的方位为"东"
时算作庄家。
点数计算：
- 非庄家得点：除得点者外，另外两名非庄家各失去得点/4，庄家失去
  非庄家失去点数的两倍（即得点/2）。
- 庄家得点：得点为非庄家得点时的 1.5 倍；除得点者外，其余三人
  各失去得点/3。
PIPI出千，从第二局到第八局每局都赢，番数分别为 x2..x8（5≤xi≤100）。
已知第一局时 PIPI 的方位 C、第一局结束时四人点数（从 PIPI 开始逆时针
输入），求第八局结束后四人的点数（从 PIPI 开始逆时针输出）。
基础得点规则：番数 x 的得点基数为 1600*x。

- 输入
第一行一个大写字母 C（E/S/W/N），表示第一局时 PIPI 的方位。
第二行四个整数 A,B,C,D，表示第一局结束时四人点数，从 PIPI 开始逆时针输入。
第三行七个整数 xi，表示第二局到第八局 PIPI 的赢牌番数。

- 输出
一行四个整数，表示第八局结束后四人的点数，从 PIPI 开始逆时针输出。

- 样例输入
E
25000 25000 25000 25000
5 5 5 5 5 5 5

- 样例输出
85000 5000 5000 5000

========================================
【解析】
1. 方位旋转：四个方位按逆时针排列为 东→南→西→北。每局结束时桌子逆时针
   旋转，相当于每个人自己的方位标签按规律变化："这局是南，下局是东"，
   即 东→北→西→南→东 的循环。第 r 局 PIPI 的方位 = 初始方位经过 (r-1)
   次旋转后的结果，其余三人同步旋转。
2. 庄家判定：某局谁的方位标签是"东"，谁就是庄家。由上面的循环，
   庄家每局沿逆时针方向换一个人。样例中 PIPI 第 1 局是东（庄家），
   第 2~8 局标签依次为 北、西、南、东、北、西、南，即第 5 局再次当庄。
3. 算点模拟（每局 PIPI 都赢，番数 xi，得点 = 1600*xi）：
   - PIPI 非庄家赢：得点 G=1600*xi；另两名非庄家各失 G/4，
     庄家失 G/2（非庄家的两倍）。
   - PIPI 是庄家赢：得点 = 1.5 * 1600 * xi；其余三人各失 G/3。
   （验证守恒：非庄家赢时 G/4+G/4+G/2 = G；庄家赢时 3*(G/3) = G，
   点数总和守恒。）
4. 实现细节：
   - 用 0,1,2,3 表示 东、北、西、南（旋转一次即 +1 模 4），PIPI 的标签
     每局 +1，其余三人同步；
   - 输入/输出都按"从 PIPI 开始逆时针"的顺序，因此只需对
     score[0..3]（score[0] 是 PIPI）按下标结算即可；
   - 番数最大 100，得点最大 2400*100 = 24 万，int 足够，
     但为稳妥使用 long long。
5. 验证样例：第 2~4、6~8 局 PIPI 非庄家，每局 +8000，两个非庄家各 -2000、
   庄家 -4000；第 5 局 PIPI 做庄，+12000，三人各 -4000。
   统计每人变化：PIPI +60000 → 85000；其余三人各 -20000 → 5000 ✓。
*/
#include <iostream>
#include <vector>
#include <string>
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    string c;
    cin >> c;
    // 输入方位转成编号：东0 北1 西2 南3
    int base = 0;
    if (c == "E") base = 0;
    else if (c == "N") base = 1;
    else if (c == "W") base = 2;
    else base = 3;
    vector<long long> sc(4);
    for (int i = 0; i < 4; i++) cin >> sc[i];
    vector<long long> x(9);
    for (int r = 2; r <= 8; r++) cin >> x[r];
    // 模拟第 2~8 局；第 r 局各人的标签 = (初始标签 + r-1) mod 4
    for (int r = 2; r <= 8; r++) {
        long long G = 1600 * x[r];          // 非庄家得点
        int pipi = (base + r - 1) % 4;      // PIPI 本局方位编号
        if (pipi == 0) {                    // PIPI 是庄家
            long long gain = G * 3 / 2;     // 庄家得点为 1.5 倍
            sc[0] += gain;
            for (int i = 1; i <= 3; i++) sc[i] -= gain / 3;
        } else {
            sc[0] += G;
            int dealer = pipi; // 庄家=标签0的人：其下标满足 (初始标签 - 下标 + r-1) ≡ 0，即下标 ≡ pipi
            for (int i = 1; i <= 3; i++)
                sc[i] -= (i == dealer ? G / 2 : G / 4);
        }
    }
    cout << sc[0] << " " << sc[1] << " " << sc[2] << " " << sc[3] << "\n";
    return 0;
}
