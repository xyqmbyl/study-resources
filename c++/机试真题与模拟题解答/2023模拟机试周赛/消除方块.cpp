/*
问题 A: 消除方块
来源：PIPIOJ 2023 模拟机试周赛 (http://pipioj.online/problem.php?cid=1055&pid=0)
时间限制: 1 Sec  内存限制: 128 MB

- 题目描述
PIPI现在有a个绿色砖块和b个白色砖块，以及一个容量为c的容器，当放入一个绿色砖块后，
容器内的白色砖块都会被消除。PIPI想把这些砖块放进该容器中，请问他是否能做到。
绿色砖块和白色砖块的体积都是1，且绿色砖块不会被消除。

- 输入
多组输入。每组输入题中描述的三个整数a,b,c(1<=a,c<=1e9,1<=b<=1e18)。

- 输出
对于每组输入，若能将所有砖块都放入容器中，输出YES，否则输出NO。

- 样例输入
6 10 7
2 5 3

- 样例输出
YES
NO

========================================
【解析】
1. 容器任意时刻装的砖块数不能超过 c。绿色砖块永远不会被消除，所以最终容器里
   至少有 a 个绿砖 → 首先必须 a <= c，否则直接输出 NO。
2. 贪心放置策略：白色砖块只有被"后面的绿色砖块"消除才能腾出空间，因此把白色
   砖块分批塞：每批白砖塞到接近满，再放一个绿砖触发消除。
   - 已放 i 个绿砖时放一批白砖，容器内有 i 个绿砖占位，本批白砖最多放 c-i-1 个
     （要给接下来要放入的绿砖留 1 个空位，否则绿砖放不进去，白砖也白塞）。
   - 放完所有 a 个绿砖后，再没有绿砖来清场了，最后一批白砖最多放 c-a 个。
3. 所以能容纳的白砖总数上限为：
        Σ_{i=0}^{a-1} (c-1-i) + (c-a)
   只要 b 不超过这个上限（并且 a<=c），就输出 YES。
4. 验证样例：
   - a=6,b=10,c=7：上限 = 6+5+4+3+2+1 + 1 = 22 >= 10 → YES
   - a=2,b=5,c=3 ：上限 = 2+1 + 1 = 4 < 5   → NO
   两例均吻合。
5. 注意 b 最大 1e18，c、a 最大 1e9，上限之和最大约 c^2/2 ≈ 5e17，用 long long
   计算即可；公式直接算，无需循环（a 可达 1e9，逐项累加会超时）。
*/
#include <iostream>
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    long long a, b, c;
    while (cin >> a >> b >> c) {
        // 绿砖永远不会被消除，最终至少要装下 a 个绿砖
        if (a > c) { cout << "NO\n"; continue; }
        // 白砖容量上限 = Σ_{i=0}^{a-1} (c-1-i) + (c-a)
        //            = a*(c-1) - a*(a-1)/2 + (c-a)
        long long cap = a * (c - 1) - a * (a - 1) / 2 + (c - a);
        cout << (b <= cap ? "YES" : "NO") << "\n";
    }
    return 0;
}
