/*
问题 B: 盒子匹配
来源：PIPIOJ 2025 公开赛 (http://pipioj.online/problem.php?cid=1068&pid=1)
时间限制: 1s  内存限制: 128MB

- 题目描述
有连续放置的编号为1到n的n个盒子，每个盒子内有且仅有一个物品，不存在空盒子，
总共有m种物品。
如果相邻盒子的物品是相同的，就会发生匹配。
求有多少种状态会发生匹配。

- 输入
共一行，包含两个整数m和n。
数据范围：1≤m≤1e5，1≤n≤1e7。

- 输出
会发生匹配的状态数，对100003取余。

- 提示
所有可能的 6 种状态为：(000)(001)(011)(100)(110)(111)。

- 样例输入
2 3

- 样例输出
6

========================================
【解析】
1. 模型转化：每个盒子独立取 m 种物品之一，全部状态共 m^n 种；"发生匹配"的
   补事件是"任意相邻两盒物品都不同"，用总数减去它即可（正难则反）。
2. 相邻互异计数：第 1 个盒子有 m 种选法；之后每个盒子只要与前一个不同，
   各有 (m-1) 种选法，且各盒选择相互独立 → 无匹配状态数 = m * (m-1)^(n-1)。
   所以答案 = m^n − m*(m-1)^(n-1)（对 100003 取余）。
3. 复杂度：n 高达 1e7，状态空间是指数级的，绝不能枚举；只需两次快速幂，
   时间 O(log n)，空间 O(1)。
4. 实现细节：
   - n=1 时不存在相邻对，公式给出 m − m*(m-1)^0 = 0，天然正确；
   - m=1 时 (m-1)=0：n>=2 则无匹配数为 0、答案为 1（唯一状态 111...1 本身
     匹配），n=1 时 0^0 按 1 处理，答案 0，公式自动成立；
   - 模意义减法可能为负，结果按 ((a − b) % p + p) % p 调整为非负；
   - 乘法用 long long 防溢出（模数 100003，乘积 < 1e10 超出 int）。
5. 验证样例：m=2, n=3：总状态 = 2^3 = 8；无匹配状态 = 2 * 1^2 = 2
   （即 010 与 101）；8 − 2 = 6，与样例输出一致 ✓，且这 6 种恰是提示中
   列出的 (000)(001)(011)(100)(110)(111)。
*/
#include <iostream>
using namespace std;

const long long MOD = 100003;

// 快速幂：(base^e) % MOD
long long qpow(long long base, long long e) {
    long long r = 1 % MOD;
    base %= MOD;
    while (e > 0) {
        if (e & 1) r = r * base % MOD;
        base = base * base % MOD;
        e >>= 1;
    }
    return r;
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    long long m, n;
    cin >> m >> n;
    long long total = qpow(m, n);                       // 全部状态数 m^n
    long long ok = m % MOD * qpow(m - 1, n - 1) % MOD;  // 无匹配状态数
    cout << ((total - ok) % MOD + MOD) % MOD << "\n";
    return 0;
}
