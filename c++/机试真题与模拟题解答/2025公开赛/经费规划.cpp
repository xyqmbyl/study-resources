/*
问题 E: 经费规划
来源：PIPIOJ 2025 公开赛 (http://pipioj.online/problem.php?cid=1068&pid=4)
时间限制: 1s  内存限制: 128MB

- 题目描述
本月实验室发了新的经费，可以购置一些办公用具。唯一的要求就是不能超出预算。
可以购买的物品分为两类：主件与附件，附件是从属于某个主件的。
如果要买归类为附件的物品，必须先买该附件所属的主件。每个主件可以有0个、1个
或2个附件，而附件不再有从属于自己的附件。
实验室需要的新物件很多，预算会超过经费。于是，实验室决定把每件物品规定了
一个重要度，分为5等：用整数1~5表示，第5等最重要。
所有物品的价格都是10的整数倍。
现在实验室的目标是在不超过经费的前提下，使每件物品的价格与重要度的乘积的
总和最大。
设第j件物品的价格为v[j]，重要度为w[j]，共选中了k件物品，编号依次为j1，j2，
…，jk，则所求的总和为：
v[j1]*w[j1]+v[j2]*w[j2]+…+v[jk]*w[jk]（其中*为乘号）
请你帮助实验室设计一个满足要求的购物单。

- 输入
输入文件的第1行，为两个正整数，用一个空格隔开：N、m，其中N表示总钱数，
m为希望购买物品的个数。
从第2行到第m+1行，第j行给出了编号为j−1的物品的基本数据，每行有3个非负整数
v,p,q，其中v表示该物品的价格，p表示该物品的重要度（1~5），q表示该物品是
主件还是附件。
如果q=0，表示该物品为主件，如果q>0，表示该物品为附件，q是所属主件的编号。

- 输出
输出文件只有一个正整数，为不超过总钱数的物品的价格与重要度乘积的总和的
最大值（<200000）。
数据范围：N<32000, m<60, v<10000。

- 样例输入
1000 5
800 2 0
400 5 1
300 5 1
400 3 0
500 2 0

- 样例输出
2200

========================================
【解析】
1. 模型转化：这是经典的"有依赖的背包"（NOIP2006 金明的预算方案）模型。
   每个主件连同它的至多 2 个附件构成一个"物品组"：买附件必须先买主件，
   所以对一个主件组只有 5 种互斥决策——
   什么都不买 / 只买主件 / 主件+附件1 / 主件+附件2 / 主件+附件1+附件2。
   价值定义为价格×重要度，即 v[j]*w[j]。
2. 算法：分组背包。把每个主件组看成一组互斥方案，容量为总钱数 N：
   dp[cap] = 前 i 个组、花费不超过 cap 的最大价值。
   转移时容量外层、方案内层、容量倒序，保证 dp[cap-cost] 读到的是本组
   处理之前的值（同组方案不会叠加）。
3. 复杂度：主件数不超过 m < 60，每组最多 5 个方案，容量 N < 32000，
   总运算量约 60 × 32000 × 5 = 9.6e6，O(m · N · 5) 时间、O(N) 空间。
4. 实现细节：
   - 读入时把附件挂到其主件（编号 q）的邻接表上，主件最多 2 个附件；
   - 只对主件（q=0）做组决策，附件跳过；附件下标在生成方案前取出；
   - 单件价值 v*w 最大 1e4*5 = 5e5，dp 用 long long 稳妥；
   - 每组先列出 5 个 (花费, 价值) 方案（附件不存在则跳过对应方案），
     花费超过当前容量的方案直接跳过。
5. 验证样例：N=1000。物品1：主件 v=800,w=2（价值1600），附件2（400,5→
   2000）、附件3（300,5→1500）；物品4：主件 400,3→1200；物品5：主件
   500,2→1000。
   - 组1 的可行方案（花费<=1000）：(0,0)、(800,1600)；
   - 处理物品4（400,1200）后：dp[1000]=max(1600, dp[600]+1200=1200)=1600，
     dp[500]=1200；
   - 处理物品5（500,1000）：dp[1000]=max(1600, dp[500]+1000=2200)=2200，
     其中 dp[500]=1200 来自"物品4"。
   买物品4+物品5（花费900）得到 2200，与样例输出一致 ✓
*/
#include <iostream>
#include <vector>
#include <algorithm>
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int N, m;
    cin >> N >> m;
    vector<int> v(m + 1), w(m + 1), q(m + 1);
    vector<vector<int>> att(m + 1);          // att[i]: 主件 i 的附件编号
    for (int i = 1; i <= m; i++) {
        cin >> v[i] >> w[i] >> q[i];
        if (q[i] > 0) att[q[i]].push_back(i);
    }
    vector<long long> dp(N + 1, 0);
    for (int i = 1; i <= m; i++) {
        if (q[i] != 0) continue;             // 附件随其主件一起决策
        // 枚举该主件组的 5 种互斥购买方案 (花费, 价值)
        vector<pair<int, long long> > opts;
        opts.push_back(make_pair(0, 0LL));
        opts.push_back(make_pair(v[i], (long long)v[i] * w[i]));
        int a1 = 0, a2 = 0;
        if (att[i].size() >= 1) a1 = att[i][0];
        if (att[i].size() >= 2) a2 = att[i][1];
        if (a1)
            opts.push_back(make_pair(v[i] + v[a1],
                (long long)v[i] * w[i] + (long long)v[a1] * w[a1]));
        if (a2) {
            opts.push_back(make_pair(v[i] + v[a2],
                (long long)v[i] * w[i] + (long long)v[a2] * w[a2]));
            if (a1)
                opts.push_back(make_pair(v[i] + v[a1] + v[a2],
                    (long long)v[i] * w[i] + (long long)v[a1] * w[a1]
                                           + (long long)v[a2] * w[a2]));
        }
        // 分组背包：容量外层倒序、方案内层，同组方案互斥
        for (int cap = N; cap >= 0; cap--) {
            for (size_t k = 0; k < opts.size(); k++) {
                int c = opts[k].first;
                if (c <= cap)
                    dp[cap] = max(dp[cap], dp[cap - c] + opts[k].second);
            }
        }
    }
    cout << dp[N] << "\n";
    return 0;
}
