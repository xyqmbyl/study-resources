/*
问题 D: 找数字
来源：PIPIOJ 2025 公开赛 (http://pipioj.online/problem.php?cid=1068&pid=3)
时间限制: 1s  内存限制: 128MB

- 题目描述
给定一个正整数 m 和一个非负整数 s 。
请你找到长度为 m 且各位数字之和为 s 的最小和最大非负整数。
要求所求非负整数不得包含前导零。

- 输入
共一行，两个整数 m,s。

- 输出
在一行内输出满足条件的最小和最大非负整数。
如果无解，则输出 -1 -1。
数据范围：前 6 个测试点满足 1≤m≤3。所有测试点满足 1≤m≤100，0≤s≤900。

- 样例输入
2 15

- 样例输出
69 96

========================================
【解析】
1. 模型转化：构造长度为 m、数位和为 s、无前导零的最小/最大数。m 可达 100，
   数会远超 long long，必须按位构造，用 string 保存结果。
2. 无解判定：m 位数字之和最大为 9m，故 s > 9m 无解；另外 s = 0 时所有位都是
   0，只有 m = 1 的"0"不含前导零，m >= 2 时无解。其余情况均有解。
3. 构造策略（贪心）：
   - 最大值：从最高位到最低位，每一段尽量放 9，即第 i 位放 min(9, 剩余 s)。
   - 最小值：首位不能为 0，先确定首位 d0 = max(1, s − 9*(m−1))——既保证
     >= 1，又给后面 m−1 位留出恰好能装下余量的空间；再从最低位往最高位
     尽量放 9（小的数字放高位才能使数最小）。
4. 复杂度：按位构造各一遍，时间 O(m)，空间 O(m)，m <= 100 忽略不计。
5. 实现细节：
   - 全程用 string 拼接，不出现任何整数转换；
   - s = 0 且 m = 1 时特判输出 "0 0"（0 是合法非负整数，首位不受 >=1 限制）；
   - s ≥ 1 时首位 d0 ∈ [1,9]：若 s − 9(m−1) ≥ 1 则 d0 恰好把余量压到后
     m−1 位；否则 d0 = 1。
6. 验证样例：m=2, s=15：
   - 最大值：第 1 位放 min(9,15)=9，剩 6，第 2 位放 6 → "96"；
   - 最小值：首位 = max(1, 15−9) = 6，剩 9，末位放 9 → "69"；
   - 输出 "69 96"，与样例一致 ✓
   另手工核对边界：m=1,s=0 → "0 0"；m=2,s=19 > 18 → "-1 -1"。
*/
#include <iostream>
#include <string>
#include <algorithm>
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int m, s;
    cin >> m >> s;
    if (s > 9 * m || (s == 0 && m > 1)) {
        cout << -1 << " " << -1 << "\n";
        return 0;
    }
    // 最大值：从高位到低位贪心放 9
    string mx;
    int rem = s;
    for (int i = 0; i < m; i++) {
        int d = min(9, rem);
        mx += char('0' + d);
        rem -= d;
    }
    // 最小值：首位确定下界，其余位从低位往高位贪心放 9
    string mn(m, '0');
    if (s == 0) {
        mn[0] = '0';                       // 此时必有 m == 1
    } else {
        int first = max(1, s - 9 * (m - 1));
        mn[0] = char('0' + first);
        rem = s - first;
        for (int i = m - 1; i >= 1 && rem > 0; i--) {
            int d = min(9, rem);
            mn[i] = char('0' + d);
            rem -= d;
        }
    }
    cout << mn << " " << mx << "\n";
    return 0;
}
