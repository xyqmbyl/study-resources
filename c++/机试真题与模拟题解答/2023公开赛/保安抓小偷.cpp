/*
问题 A: 保安抓小偷
来源：PIPIOJ 2023 公开赛 (http://pipioj.online/problem.php?cid=1054&pid=0)
时间限制: 1 Sec  内存限制: 128 MB

- 题目描述
在一片10*10的空地上（边界外视为障碍），其中有些格子是障碍('*')。
保安S和小偷T每分钟同时行动一次：他们都有一个固定的朝向（初始朝北），
每分钟沿自己当前朝向走一格；如果前方一格是障碍（或走出地图），则原地不动，
只把朝向顺时针旋转90度。保安一直想抓小偷，小偷毫不知情。
问最少多少分钟后保安能与小偷处在同一格；若永远抓不到，输出0。

- 输入
10行，每行10个字符，'.'为空地，'*'为障碍，'S'为保安初始位置，'T'为小偷初始位置。

- 输出
若能抓到，输出最少分钟数；否则输出0。

- 样例输入
..........
....*.....
..S.......
..........
....*.....
..........
..........
.....T....
..........
..........

- 样例输出
（按实际地图模拟输出）

========================================
【解析】
这是经典 USACO "The Cow Run / 逮捕奶牛" 模型的变形：
1. 状态 = (保安坐标, 保安朝向, 小偷坐标, 小偷朝向)。两人规则完全一致，
   只是初始位置不同，可以共用同一个移动函数：若前方是障碍就顺时针转向，
   否则前进一格。方向编号 0=北、1=东、2=南、3=西，顺时针恰好 +1。
2. 状态总数只有 100 * 4 * 100 * 4 = 160000 种，把状态编码成整数
        z = sx + sy*10 + tx*100 + ty*1000 + sd*10000 + td*40000
   用布尔数组标记该状态是否出现过。
3. 每分钟：先检查两人是否同格（同格即抓到，输出当前分钟数）；否则记录状态、
   双方各走一步。若某个状态再次出现，说明之后将无限循环、永远抓不到，
   输出 0。
4. 因为状态有限且转移确定，模拟不会超时；这是"状态图上找环"的通用技巧——
   只要有重复状态即可断定死循环。
5. 小技巧：把地图四周（下标 0 和 11）也填成 '*'，就可以免去越界判断。
*/
#include <iostream>
#include <string>
#include <vector>
using namespace std;

struct Person {
    int x, y, d;  // 坐标与朝向，0北 1东 2南 3西
    void step(const vector<string>& mp) {
        int nx = x + (d == 2) - (d == 0);
        int ny = y + (d == 1) - (d == 3);
        if (mp[nx][ny] == '*') {  // 前方是障碍：只转向不前进
            d = (d + 1) % 4;
        } else {
            x = nx;
            y = ny;
        }
    }
};

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    vector<string> mp(12, string(12, '*'));  // 四周设为 '*' 作为围墙
    Person s{1, 1, 0}, t{1, 1, 0};           // 保安 S / 小偷 T
    for (int i = 1; i <= 10; i++) {
        string row;
        cin >> row;
        for (int j = 1; j <= 10; j++) {
            mp[i][j] = row[j - 1];
            if (row[j - 1] == 'S') s = {i, j, 0};
            if (row[j - 1] == 'T') t = {i, j, 0};
        }
    }
    vector<bool> vis(160005, false);  // 状态编码是否出现过
    int ans = 0;
    while (s.x != t.x || s.y != t.y) {  // 未在同一格：继续模拟
        int code = s.x + s.y * 10 + t.x * 100 + t.y * 1000 + s.d * 10000 + t.d * 40000;
        if (vis[code]) {  // 状态重复 → 死循环
            cout << 0 << "\n";
            return 0;
        }
        vis[code] = true;
        s.step(mp);  // 保安走一步
        t.step(mp);  // 小偷走一步
        ans++;       // 分钟数 +1
    }
    cout << ans << "\n";
    return 0;
}
