/*
问题 F: 巨人排排站
来源：PIPIOJ 2024 公开赛 (http://pipioj.online/problem.php?cid=1056&pid=5)
时间限制: 1s  内存限制: 128MB

- 题目描述
巨人王国里有n个人站成一排，从左到右编号为1~n。
每个人都看向右边，且人的视力是有限的，最多只能看到右边k个人。
请找出每个人视线范围内（包括自己）身高最高的人的编号（如果有人身高相同，
只会看到离自己最近的那个人）。

- 输入
第一行输入人数n和视力k(n,k<=2e6)，
第二行输入n个整数，依次表示从左到右每个人的身高，每个人的身高不超过5e4。

- 输出
输出每个人视线范围内（包括自己）身高最高的人的编号。

- 样例输入
5 1
2 3 1 4 5

- 样例输出
2 2 4 5 5

========================================
【解析】
1. 模型转化：对每个 i 求 [i, min(i+k, n)] 内身高最大者的下标（相同身高取
   最靠左即离 i 最近者），即窗口大小 k+1 的滑动窗口最大值（下标形式）。
2. 算法：单调队列 O(n)。从右往左处理 i，队列中保存下标，自队首向队尾
   下标递增、身高严格递减（队首 = 窗口内最大者）：
   - 新元素 i 从队首一侧进入：弹出队首中身高 <= a[i] 的元素——它们离 i
     更远又不高过 i（相同身高也弹，保证"相同取最近"）；
   - 从队尾一侧弹出下标 > i+k 的越界元素（i 减小时窗口右端点 i+k 也在
     减小，出界者不会再回来）；
   - 此时队首即 ans[i]。
3. 复杂度：每个下标至多进队、出队各一次，O(n)；n ≤ 2e6。
   用数组手写队列避免 deque 常数；输出量大，一次性拼接。
4. 实现细节：队列 q 以 head 为队首（下标小的一端）、tail 为队尾，
   从 head 端压入（--head）、从 tail 端弹出；q 数组开 n+2 足够。
5. 验证样例：n=5, k=1，a=[2,3,1,4,5]：
   i=5: 队列[5]，ans=5；i=4: a[5]=5>4，队列[4,5]，ans=5；
   i=3: 队列[3,4]（5 越出窗口 [3,4]），max=4 → ans=4；
   i=2: 弹出 a[3]=1<=3，队列[2,4]，ans=2；i=1: a[2]=3>2，队列[1,2]，
   4 越出窗口 [1,2]，ans=2。
   输出 "2 2 4 5 5"，与样例一致 ✓。
*/
#include <iostream>
#include <vector>
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int n, k;
    while (cin >> n >> k) {
        vector<int> a(n + 1);
        for (int i = 1; i <= n; i++) cin >> a[i];
        vector<int> q(n + 2);
        int head = n + 1, tail = n;   // 空队列: head > tail
        vector<int> ans(n + 1);
        for (int i = n; i >= 1; i--) {
            // 从队首压入 i，弹掉更远且不比它高的
            while (head <= tail && a[q[head]] <= a[i]) head++;
            q[--head] = i;
            // 从队尾弹掉越出窗口 [i, i+k] 的下标
            while (q[tail] > i + k) tail--;
            ans[i] = q[head];
        }
        for (int i = 1; i <= n; i++) {
            cout << ans[i];
            cout << (i < n ? ' ' : '\n');
        }
    }
    return 0;
}
