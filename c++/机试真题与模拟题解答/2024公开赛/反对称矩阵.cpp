/*
问题 C: 反对称矩阵
来源：PIPIOJ 2024 公开赛 (http://pipioj.online/problem.php?cid=1056&pid=2)
时间限制: 1s  内存限制: 128MB

- 题目描述
反对称矩阵是指方阵A对于任意的i≠j，满足Aij不等于Aji。
现在有一个n*n的01方阵，其中还有一些空没有填，现在要求你使用0或1补全该方阵，
问是否能使它成为反对称矩阵。
如果可以变为反对称矩阵，把矩阵的每行连接成一行，输出字典序最大的那个字符串，
否则输出impossible。

- 输入
多组输入。
第一行输入矩阵的大小n（1<=n<=200）。
接下来输入一个只包含-或0或1的n*n的矩阵，
-代表为空，0和1代表已经填了的数。

- 输出
输出由填完矩阵得到的字典序最大的字符串。
如果填不出符合要求的矩阵，输出impossible。

- 提示
第一个用例得到的矩阵为
110
010
111

- 样例输入
3
1-0
--0
-1-
2
-0
0-

- 样例输出
110010111
impossible

========================================
【解析】
1. 模型转化：约束 A[i][j] != A[j][i]（01 矩阵下即 A[i][j] = 1 - A[j][i]）
   只把关于主对角线的一对位置 (i,j) 与 (j,i) 绑定在一起，不同的数对之间
   互不影响；对角线位置 (i,i) 完全自由（约束只对 i≠j）。
2. 因此逐数对独立判定与贪心：
   - 若 A[i][j] 与 A[j][i] 都已给定：必须一个 0 一个 1，否则 impossible；
   - 若恰有一个给定：另一个取反；
   - 若两者都为空：为使拼接串字典序最大，因 i<j 时 (i,j) 在串中先出现，
     令 A[i][j] = 1、A[j][i] = 0。
   - 对角线为空时填 1（字典序最大）。
3. 由于各数对独立，上述贪心即为字典序最大的可行填法；存在任何一对矛盾
   （两个给定值相同）则输出 impossible。
4. 复杂度：O(n^2)，n ≤ 200，多组输入轻松通过。
5. 验证样例：
   - 用例1：(0,2) 给定 0 → (2,0)=1；(1,2) 给定 0、(2,1) 给定 1，满足互异；
     (0,1)/(1,0) 均空 → 填 (0,1)=1,(1,0)=0；对角线 (1,1),(2,2) 空填 1，
     (0,0)=1。得到 110/010/111，拼接 "110010111" ✓。
   - 用例2：(0,1)=0 且 (1,0)=0，相同 → impossible ✓。
*/
#include <iostream>
#include <vector>
#include <string>
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int n;
    while (cin >> n) {
        vector<string> g(n);
        for (int i = 0; i < n; i++) cin >> g[i];
        bool ok = true;
        // 处理对角线：自由，空则填 1（字典序最大）
        for (int i = 0; i < n && ok; i++)
            if (g[i][i] == '-') g[i][i] = '1';
        // 处理数对 (i,j)/(j,i)，i < j
        for (int i = 0; i < n && ok; i++) {
            for (int j = i + 1; j < n && ok; j++) {
                char a = g[i][j], b = g[j][i];
                if (a == '-' && b == '-') {
                    g[i][j] = '1';  // (i,j) 在拼接串中先出现，取 1
                    g[j][i] = '0';
                } else if (a == '-') {
                    g[i][j] = (b == '1' ? '0' : '1');
                } else if (b == '-') {
                    g[j][i] = (a == '1' ? '0' : '1');
                } else if (a == b) {
                    ok = false;  // 给定值相同，违反 Aij != Aji
                }
            }
        }
        if (!ok) {
            cout << "impossible" << "\n";
        } else {
            string ans;
            for (int i = 0; i < n; i++) ans += g[i];
            cout << ans << "\n";
        }
    }
    return 0;
}
