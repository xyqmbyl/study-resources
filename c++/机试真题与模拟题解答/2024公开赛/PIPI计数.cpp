/*
问题 A: PIPI计数
来源：PIPIOJ 2024 公开赛 (http://pipioj.online/problem.php?cid=1056&pid=0)
时间限制: 1s  内存限制: 128MB

- 题目描述
给定一个正整数n，请求出1~n中能够被2或3或5整除的数的数量。

- 输入
多组输入。
每组输入一个正整数n(1<=n<=1e5)。

- 输出
对于每组输入，输出1~n中能够被2,3,5整除的数的数量。

- 样例输入
3

- 样例输出
2

========================================
【解析】
1. 模型转化：求 1~n 中被 2、3、5 至少一个整除的数的个数，经典的容斥原理
   (inclusion-exclusion) 计数：
        |A∪B∪C| = |A|+|B|+|C| - |A∩B| - |A∩C| - |B∩C| + |A∩B∩C|
   其中 |被 d 整除的数的个数| = n / d（整数除法，向下取整）。
2. 三个集合的交即被 lcm 整除：lcm(2,3)=6, lcm(2,5)=10, lcm(3,5)=15,
   lcm(2,3,5)=30，所以答案为：
        n/2 + n/3 + n/5 - n/6 - n/10 - n/15 + n/30
3. 复杂度：每组 O(1)，多组输入直接读入即可（n ≤ 1e5，数据规模极小）。
4. 实现细节：整数除法天然向下取整，直接用 int/long long 均可；
   注意符号：两两交减、三者交加，不要写漏。
5. 验证样例：n=3：3/2=1, 3/3=1, 3/5=0, 3/6=0, 3/10=0, 3/15=0, 3/30=0，
   答案 = 1+1+0-0-0-0+0 = 2，与样例输出 2 一致（1~3 中 2、3 被整除）✓。
*/
#include <iostream>
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    long long n;
    while (cin >> n) {
        long long ans = n / 2 + n / 3 + n / 5
                      - n / 6 - n / 10 - n / 15
                      + n / 30;
        cout << ans << "\n";
    }
    return 0;
}
